#!/usr/bin/env python3
"""
Generate the per-file attribution table for Wikimedia Commons audio.

CC BY-SA requires crediting the actual uploader/author and exact license of
EACH file, not a blanket "Wikimedia Commons, CC-something" statement. Kaikki
only gives us the download URL; this script extracts the Commons file title
from it and queries the Commons API for the real license/author metadata,
then writes the result to ATTRIBUTION_AUDIO.md.

Usage: python3 tooling/build_attribution.py [--level A1]
"""
import csv
import json
import re
import sys
import time
import urllib.parse
import urllib.request
from pathlib import Path

FINAL_CSV = Path("content/kelly_final.csv")
OUT_MD = Path("ATTRIBUTION_AUDIO.md")
API_URL = "https://commons.wikimedia.org/w/api.php"
HEADERS = {"User-Agent": "SwedishAnkiDeckBuilder/1.0 (personal language-learning project; contact vitords.42@gmail.com) Python-urllib"}

# e.g. https://upload.wikimedia.org/wikipedia/commons/transcoded/3/34/Sv-ett.ogg/Sv-ett.ogg.mp3
#   -> File:Sv-ett.ogg
COMMONS_FILENAME_RE = re.compile(r"/transcoded/[0-9a-f]/[0-9a-f]{2}/([^/]+)/")


def commons_title_from_url(url):
    m = COMMONS_FILENAME_RE.search(url)
    if not m:
        return None
    # The URL has the filename percent-encoded (parens, accented letters,
    # etc.), so decode it to get the actual Commons page title, or API lookups
    # for anything with such characters (most non-ASCII Swedish words) fail.
    return f"File:{urllib.parse.unquote(m.group(1))}"


def fetch_metadata(titles):
    """Query the Commons API for a batch of up to 50 file titles, returns
    {title: {license, license_url, artist, usage_terms}}."""
    params = {
        "action": "query", "titles": "|".join(titles), "prop": "imageinfo",
        "iiprop": "extmetadata", "format": "json",
    }
    url = API_URL + "?" + urllib.parse.urlencode(params)
    req = urllib.request.Request(url, headers=HEADERS)
    with urllib.request.urlopen(req, timeout=20) as resp:
        data = json.loads(resp.read())
    out = {}
    for page in data.get("query", {}).get("pages", {}).values():
        title = page.get("title")
        infos = page.get("imageinfo")
        if not infos:
            continue
        meta = infos[0].get("extmetadata", {})
        out[title] = {
            "license": meta.get("LicenseShortName", {}).get("value", "unknown"),
            "license_url": meta.get("LicenseUrl", {}).get("value", ""),
            "artist": re.sub(r"<[^>]+>", "", meta.get("Artist", {}).get("value", "")).strip(),
            "usage_terms": meta.get("UsageTerms", {}).get("value", ""),
        }
    return out


def main():
    level = None
    if "--level" in sys.argv:
        level = sys.argv[sys.argv.index("--level") + 1]

    rows = list(csv.DictReader(open(FINAL_CSV, encoding="utf-8")))
    if level:
        rows = [r for r in rows if r["cefr"] == level]

    entries = []  # (word, pos, commons_title, source_url)
    for r in rows:
        if r.get("audio_source") != "wikimedia" or not r.get("audio_credit_url"):
            continue
        title = commons_title_from_url(r["audio_credit_url"])
        if title:
            entries.append((r["word"], r["pos"], title, r["audio_credit_url"]))

    unique_titles = sorted({e[2] for e in entries})
    print(f"Looking up metadata for {len(unique_titles)} unique Commons files...")
    metadata = {}
    for i in range(0, len(unique_titles), 50):
        batch = unique_titles[i : i + 50]
        try:
            metadata.update(fetch_metadata(batch))
        except Exception as e:
            print(f"WARNING: batch starting at {i} failed: {e}")
        time.sleep(1.0)

    lines = [
        "# Wikimedia Commons audio attribution",
        "",
        "Generated by [`tooling/build_attribution.py`](tooling/build_attribution.py). Each row is one audio file bundled",
        "under [`content/audio/`](content/audio/), sourced from Wikimedia Commons via the Kaikki/Wiktextract",
        "Wiktionary dump. Per Commons policy, each file carries its own license and",
        "author, so don't assume they all match.",
        "",
        "| Word | POS | Commons file | License | Author |",
        "|---|---|---|---|---|",
    ]
    for word, pos, title, url in entries:
        meta = metadata.get(title, {})
        license_str = meta.get("license", "unknown")
        license_url = meta.get("license_url", "")
        license_cell = f"[{license_str}]({license_url})" if license_url else license_str
        artist = meta.get("artist") or "(not machine-readable on Commons; see file page)"
        page_url = "https://commons.wikimedia.org/wiki/" + urllib.parse.quote(title)
        lines.append(f"| {word} | {pos} | [{title}]({page_url}) | {license_cell} | {artist} |")

    OUT_MD.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {OUT_MD} ({len(entries)} rows, {len(metadata)}/{len(unique_titles)} files resolved)")


if __name__ == "__main__":
    main()
